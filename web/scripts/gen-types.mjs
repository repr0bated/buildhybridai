// Generates everything the web app derives from the shared JSON Schema registry
// (app/src/main/assets/schemas): TypeScript types, one schema bundle for ajv, and
// firestore.rules for the sync documents. Nothing here is hand-written per method.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const dir = process.env.CG_SCHEMAS ?? resolve(root, '../app/src/main/assets/schemas');
const out = join(root, 'src/generated');
mkdirSync(out, { recursive: true });

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));
const registry = readJson(join(dir, 'registry.json'));

const bundle = {
  registry,
  root: {},
  methods: {},
  sync: {},
};
for (const f of ['scam_verdict', 'deep_analysis', 'subscription_check', 'message_source']) {
  bundle.root[f] = readJson(join(dir, `${f}.schema.json`));
}
for (const m of registry.methods) {
  bundle.methods[m.id] = { input: readJson(join(dir, m.input)), output: readJson(join(dir, m.output)) };
}
for (const f of readdirSync(join(dir, 'sync')).filter((x) => x.endsWith('.schema.json')).sort()) {
  bundle.sync[f.replace('.schema.json', '')] = readJson(join(dir, 'sync', f));
}
writeFileSync(join(out, 'schemas.json'), JSON.stringify(bundle));

// ---- TypeScript types ----
const all = [
  ...Object.values(bundle.root),
  ...Object.values(bundle.methods).flatMap((m) => [m.input, m.output]),
  ...Object.values(bundle.sync),
];
let ts = '/* AUTO-GENERATED by scripts/gen-types.mjs from the JSON Schema registry. Do not edit. */\n/* eslint-disable */\n\n';
const seen = new Set();
for (const s of all) {
  if (seen.has(s.title)) continue;
  seen.add(s.title);
  const { $schema, $id, ...rest } = s;
  // Nested `title`s are UI labels, not type names: drop them so the generator inlines property types.
  const strip = (n, root = false) => Array.isArray(n) ? n.map((x) => strip(x)) : n && typeof n === 'object'
    ? Object.fromEntries(Object.entries(n).filter(([k, v]) => !(k === 'title' && !root && typeof v === 'string')).map(([k, v]) => [k, k === 'properties' ? Object.fromEntries(Object.entries(v).map(([pk, pv]) => [pk, strip(pv)])) : strip(v)])) : n;
  ts += (await compile(strip(rest, true), s.title, { declareExternallyReferenced: false, ignoreMinAndMaxItems: true, bannerComment: '', additionalProperties: false, strictIndexSignatures: false, format: false })) + '\n';
}
ts += `export const METHOD_IDS = ${JSON.stringify(registry.methods.map((m) => m.id))} as const;\n`;
ts += `export type MethodId = (typeof METHOD_IDS)[number];\n`;
writeFileSync(join(out, 'types.ts'), ts);

// ---- Firestore security rules from the sync schemas ----
const cond = (name, p) => {
  const types = Array.isArray(p.type) ? p.type : [p.type];
  const parts = [];
  for (const t of types) {
    if (t === 'string') {
      let c = `d.${name} is string`;
      if (p.minLength) c += ` && d.${name}.size() >= ${p.minLength}`;
      if (p.maxLength) c += ` && d.${name}.size() <= ${p.maxLength}`;
      if (p.enum) c += ` && d.${name} in ${JSON.stringify(p.enum.filter((x) => x !== null))}`;
      parts.push(`(${c})`);
    } else if (t === 'integer') {
      let c = `d.${name} is int`;
      if (p.minimum !== undefined) c += ` && d.${name} >= ${p.minimum}`;
      if (p.maximum !== undefined) c += ` && d.${name} <= ${p.maximum}`;
      parts.push(`(${c})`);
    } else if (t === 'boolean') parts.push(`d.${name} is bool`);
    else if (t === 'array') parts.push(`(d.${name} is list${p.maxItems ? ` && d.${name}.size() <= ${p.maxItems}` : ''})`);
    else if (t === 'object') parts.push(`d.${name} is map`);
    else if (t === 'null') parts.push(`d.${name} == null`);
  }
  if (p.enum && p.enum.includes(null) && !types.includes('null')) parts.push(`d.${name} == null`);
  return parts.join(' || ');
};
const idField = { sync_receipt: 'id', sync_verdict: 'id', sync_sender_rule: 'key', sync_subscription: 'key', sync_private_flag: 'key', sync_content: 'itemId', sync_companion_alert: 'id' };
let rules = `// AUTO-GENERATED by web/scripts/gen-types.mjs from app/src/main/assets/schemas/sync/*.schema.json.\n`;
rules += `// Each user can read and write only users/{uid}/...; every document must match its sync schema.\n`;
rules += `// The content collection can only be written while settings/main.syncMessageContent is true.\n`;
rules += `rules_version = '2';\nservice cloud.firestore {\n  match /databases/{database}/documents {\n`;
rules += `    function owner(uid) { return request.auth != null && request.auth.uid == uid; }\n`;
rules += `    function contentSyncOn(uid) {\n      return exists(/databases/$(database)/documents/users/$(uid)/settings/main)\n        && get(/databases/$(database)/documents/users/$(uid)/settings/main).data.syncMessageContent == true;\n    }\n\n`;
for (const [name, s] of Object.entries(bundle.sync)) {
  const coll = s['x-firestore'];
  const m = coll.match(/^users\/\{uid\}\/([a-zA-Z]+)\/(.+)$/);
  const [, c, docPart] = m;
  const idKey = docPart === 'main' ? null : idField[name];
  const keys = Object.keys(s.properties);
  const checks = [`d.keys().hasOnly(${JSON.stringify(keys)})`, `d.keys().hasAll(${JSON.stringify(s.required)})`];
  for (const [k, p] of Object.entries(s.properties)) {
    const c1 = cond(k, p);
    checks.push(s.required.includes(k) ? `(${c1})` : `(!('${k}' in d) || ${c1})`);
  }
  if (idKey) checks.push(`d.${idKey} == id`);
  const matchId = docPart === 'main' ? 'main' : '{id}';
  rules += `    match /users/{uid}/${c}/${matchId} {\n`;
  rules += `      function valid(${idKey ? 'id' : ''}) {\n        let d = request.resource.data;\n        return ${checks.join('\n          && ')};\n      }\n`;
  rules += `      allow read, delete: if owner(uid);\n`;
  const gate = name === 'sync_content' ? ' && contentSyncOn(uid)' : '';
  rules += `      allow create, update: if owner(uid)${gate} && valid(${idKey ? 'id' : ''});\n    }\n\n`;
}
rules += `    match /{document=**} { allow read, write: if false; }\n  }\n}\n`;
writeFileSync(join(root, 'firestore.rules'), rules);
console.log(`generated: ${seen.size} types, ${registry.methods.length} methods, ${Object.keys(bundle.sync).length} sync schemas, firestore.rules`);
